"""Report 5.0: brings sections II.2 and II.3 up to the test reports of 27/11/2026 (content only, styles kept).

Numbers are read from the workbooks, not typed:
* UT  Report-5.1_Unit_Test.xlsx      Rounds 1-3 (Round 3 = per-test regression run of every service, #521)
* IT  Report-5.2_Test_Report.xlsx    Rounds 1-2 (Bruno, api-gateway / user / product, GoldenFlow)
* ST  Report-5.3_System_Test_FRs.xlsx    Rounds 1-2 (run-e2e-full.sh, BF-01..BF-07 and security, #676)
* AT  Report-5.5_Acceptance_Test.xlsx Rounds 1-3 (Playwright, manual rows Pending, #677)
* defects  Report-5.6_Defect_Log.xlsx (level, severity, status of each DEF)
A round's Total counts its Passed, Failed and Pending cases; N/A cases (not part of that round, or not implemented
yet) are left out of Total and named in the Note.

    python r5_test_results_2711.py [--book NAME=path ...]   (default: the workbooks next to Report 5.0)
"""
import argparse
import collections
import sys
from pathlib import Path

import docx
import openpyxl
from docx.oxml.ns import qn

sys.path.insert(0, str(Path(__file__).parent))
from docxedit import fill_change_log, find, insert_copy_after, next_table, set_cell_text, set_par_text  # noqa: E402

REPORTS = Path(__file__).resolve().parents[1]
DOC = REPORTS / "Report-5.0_Test Documentation.docx"
BOOKS = {"5.1": "Report-5.1_Unit_Test.xlsx", "5.2": "Report-5.2_Test_Report.xlsx", "5.3": "Report-5.3_System_Test_FRs.xlsx",
         "5.5": "Report-5.5_Acceptance_Test.xlsx", "5.6": "Report-5.6_Defect_Log.xlsx"}
parser = argparse.ArgumentParser()
parser.add_argument("--book", action="append", default=[], help="5.x=path to read that workbook from elsewhere")
args = parser.parse_args()
paths = {k: REPORTS / v for k, v in BOOKS.items()}
paths.update({k: Path(v) for k, v in (b.split("=", 1) for b in args.book)})


def rounds(book, prefix):
    """per round (1..3): Counter of results over every case row (ID starting with prefix) of the module sheets"""
    wb = openpyxl.load_workbook(paths[book], read_only=True, data_only=True)
    out = [collections.Counter() for _ in range(3)]
    for ws in wb.worksheets[3:]:
        for row in ws.iter_rows(min_row=12, max_col=12, values_only=True):
            if isinstance(row[0], str) and row[0].startswith(prefix):
                for i, col in enumerate((5, 8, 11)):
                    if row[col]:
                        out[i][row[col]] += 1
    return out


def defects():
    wb = openpyxl.load_workbook(paths["5.6"], read_only=True)
    header, out = None, []
    for row in wb.worksheets[-1].iter_rows(values_only=True):
        if row and row[0] == "Defect ID":
            header = list(row)
        elif header and row and str(row[0] or "").startswith("DEF-"):
            out.append(dict(zip(header, row)))
    return out


LEVELS = {"UT": rounds("5.1", "UTC"), "IT": rounds("5.2", "ITC"), "ST": rounds("5.3", "STC"),
          "AT": rounds("5.5", "ATC")}
DEFECTS = defects()


def cell(level, rnd, metric):
    c = LEVELS[level][rnd]
    if not c:
        return "-"
    if metric == "Total":
        return c["Passed"] + c["Failed"] + c["Pending"]
    return c[metric]


def plain_total(values):
    nums = [v for v in values if isinstance(v, int)]
    return sum(nums) if nums else "-"


def extra(level, rnd):
    c = LEVELS[level][rnd]
    parts = [f"{c[k]} {k}" for k in ("Pending", "N/A") if c[k]]
    return f"{level} {', '.join(parts)}" if parts else ""


d = docx.Document(DOC)


def rows(tbl):
    return tbl.findall(qn("w:tr"))


def write_row(tr, values):
    for tc, v in zip(tr.findall(qn("w:tc")), values):
        if v is not None:
            set_cell_text(tc, str(v))


# ---------------------------------------------------------------- II.2 test case workbooks
set_par_text(find(d, "The test cases are kept in two workbooks"),
             "The test cases are kept in five workbooks, all on the provided template and generated by scripts under "
             "scripts/unit-test-report/ from real runs:")
other = find(d, "Other Test Cases (IT, ST): Report-5.2_Test_Report.xlsx")
set_par_text(other, "Integration Test Cases (IT): Report-5.2_Test_Report.xlsx, filled from the Bruno collection "
                    "backend/bruno for api-gateway, user-service and product-service, plus the GoldenFlow module (the "
                    "whole stack built from a commit). Each round is a real Bruno run kept in "
                    "scripts/unit-test-report/results/.")
anchor = other
for text in ("System Test Cases (ST): Report-5.3_System_Test_FRs.xlsx, one sheet per business flow BF-01..BF-07 plus "
             "security, one row per Bruno step of backend/bruno/e2e and backend/bruno/security; rounds are runs of "
             "backend/scripts/run-e2e-full.sh on a fresh Docker Compose stack, with an Actual Results column.",
             "UI and Acceptance Test Cases (AT): Report-5.5_Acceptance_Test.xlsx, one sheet per role; the automated "
             "rows read their rounds from Playwright runs (frontend/tests/qa), the manual rows are checked on the "
             "demo stack.",
             "Defect Log: Report-5.6_Defect_Log.xlsx, every real test failure with its run, cause, fix and re-test; "
             "the Defect IDs columns of 5.1-5.4 point at it."):
    anchor = insert_copy_after(anchor, other)
    set_par_text(anchor, text)

# ---------------------------------------------------------------- II.3 intro
opened = [x for x in DEFECTS if x["Status"] == "Open"]
set_par_text(find(d, "Results as of 25/11/2026"),
             "Results as of 27/11/2026, read from the workbooks of II.2 (UT Report-5.1, IT Report-5.2, ST Report-5.3, "
             "AT Report-5.4) and the defect log Report-5.5. A round's Total counts its Passed, Failed and Pending cases; "
             "N/A cases (not part of that round, or not implemented yet) are left out and named in the Note. Round 1 "
             "is each level's first run; Round 2 confirms the fixes of Round 1 and is a regression run; UT Round 3 is "
             "the per-test regression run of every service (#521) and AT Round 3 the Playwright re-run with the manual "
             "acceptance rows. A defect is an entry of Report-5.5; its severity there (High, Medium, Low) is counted "
             "below as Critical, Major and Minor. "
             f"{len(opened)} defects are still open: " + ", ".join(f"{x['Defect ID']} ({x['Fix (issue / PR)']})"
                                                                   for x in opened) + ".")

# ---------------------------------------------------------------- II.3.1 Summary Table
NOTES = [
    ["UT: Report-5.1 Round 1 (31/10/2026, later modules on their merge date). IT: Report-5.2 Round 1 (25/11/2026; "
     "GoldenFlow 27/11). ST: Report-5.3 run-20261127-1603 on 94d46500. AT: Report-5.4 CI run 45484721149 on 0088280c"
     + "; " + "; ".join(x for x in (extra(lv, 0) for lv in LEVELS) if x),
     "",
     "UT: AnalyticsTopology UTC004 (DEF-01). IT: 17 cases on DEF-16 (#647) and GoldenFlow on DEF-17. ST: 12 security "
     "cases on DEF-15 (#663) and BF04-250 on DEF-18 (#685). AT: DEF-09"],
    ["UT: re-run on 07/11/2026 of the modules merged by 31/10, and UTC004 after #449. IT: whole collection after "
     "PR #648 and GoldenFlow after PR #678. ST: run-20261127-1630 after PR #686. AT: CI run 45488633271 on f233904e"
     + "; " + "; ".join(x for x in (extra(lv, 1) for lv in LEVELS) if x),
     "",
     "ST: the 12 DEF-15 cases (#663 still open). AT: FE-015 on DEF-10"],
    ["UT: regression run of every service, read per test from surefire / Jest (scripts/unit-test-report/results/"
     "unit-round3*); 614e6ab6 for api-gateway, product-service, user-service, 94d46500 for the others. AT: Playwright "
     "on 94d46500" + "; " + "; ".join(x for x in (extra(lv, 2) for lv in LEVELS) if x),
     "", ""],
]
summary = next_table(find(d, "3.1 Summary Table"))
data_rows = rows(summary)[1:]
assert len(data_rows) == 9, "the summary table should hold 3 rounds x (Total, Passed, Failed)"
for r in range(3):
    for j, metric in enumerate(("Total", "Passed", "Failed")):
        values = [cell(lv, r, metric) for lv in LEVELS]
        write_row(data_rows[3 * r + j], [f"Round #{r + 1}" if j == 0 else None, metric, *values,
                                         plain_total(values), NOTES[r][j]])

# ---------------------------------------------------------------- II.3.2 Test Levels' Defects
SEVERITY = {"High": "Critical", "Medium": "Major", "Low": "Minor"}


def level_of(x):
    return x["Level"].split("/")[0]  # DEF-11 (UT/IT) is counted where it was found first, UT


by_level = collections.Counter(level_of(x) for x in DEFECTS)
open_by = {s: collections.Counter(level_of(x) for x in opened if SEVERITY[x["Severity"]] == s)
           for s in ("Critical", "Major")}
levels = next_table(find(d, "3.2 Test Levels"))
_, tot, crit, major = rows(levels)
write_row(tot, ["Total Defects", "-", *(by_level[lv] or "-" for lv in LEVELS), len(DEFECTS),
                "Report-5.5 DEF-01..DEF-%02d. DEF-11 (UT/IT) is counted under UT. DEF-09/10 are the Playwright "
                "failures that Report-5.4 shows in its AT rounds; Report-5.5 files them at ST" % len(DEFECTS)])
for tr, s in ((crit, "Critical"), (major, "Major")):
    names = ", ".join(f"{x['Defect ID']} {x['Level']} ({x['Fix (issue / PR)']})" for x in opened
                      if SEVERITY[x["Severity"]] == s)
    write_row(tr, [f"Open Defects ({s})", "-", *(open_by[s][lv] for lv in LEVELS), sum(open_by[s].values()),
                   names or "None open"])

# ---------------------------------------------------------------- II.3.3 Work Product's Defects
products = next_table(find(d, "3.3 Work Product"))
package = rows(products)[1]
modules = collections.Counter(str(x["Module"]).split(" (")[0] for x in DEFECTS)
write_row(package, ["Software Package", "-", *(by_level[lv] or "-" for lv in LEVELS), len(DEFECTS),
                    "By module: " + ", ".join(f"{m} {n}" for m, n in modules.most_common())])

# ---------------------------------------------------------------- Change log
fill_change_log(next_table(find(d, "Change Log", tag="w:p")),
                ["27/11/2026", "M", "Hai Long",
                 "Section II.2: five workbooks (Report-5.3 ST, 5.4 AT, 5.5 defect log added). Section II.3: summary "
                 "table with UT Round 3 of every service, ST rounds 1-2 and AT rounds 1-3, defects by level and work "
                 "product from Report-5.5"])

d.save(DOC)
print("saved", DOC.name)
for lv, rs in LEVELS.items():
    print(lv, [dict(c) for c in rs])
print("defects", dict(by_level), "open", [x["Defect ID"] for x in opened])
