"""BF-03 Contract Signing & Activation (activity diagram, UML / Visual Paradigm notation).

Content synced with the Phase 2 design (#662): eligibility rechecked at both signature steps (D37), funding schedule
guard (D67), activation recovery with the 5-business-day cancel window, refund before ACTIVATION_FAILED.
Final nodes sit in the parties' lanes.
"""
import sys
from pathlib import Path

sys.path.insert(0, str(Path(__file__).resolve().parents[1] / "tools"))
from vpdiagram import Diagram  # noqa: E402

d = Diagram("bf03", width=910, height=1665)
for name, w in (("Buyer", 180), ("Seller", 180), ("System", 360), ("Operator", 190)):
    d.lane(name, w)
B, S, O = d.center("Buyer"), d.center("Seller"), d.center("Operator")
Y = 520  # main System column, left of the lane centre to leave room for side branches
CH = 735  # loop-back channel, right of the System lane

d.initial("start", B, 55)
d.action("a1", B, 115, "1. Create an offer\non an eligible listing", w=160)
d.action("a2", Y, 115, "2. Validate eligibility and\nterms; reserve the listing\nquantity", w=250)
d.action("a3", S, 200, "3. Review or revise\nthe terms (either\nparty, before the\nfirst signature)", w=165)
d.decision("d1", S, 275)
d.action("a4", S, 340, "4. Withdraw the offer\n(either party, before\nthe second signature)", w=165)
d.action("a5", Y, 340, "5. Mark WITHDRAWN, release\nthe reservation, notify\nthe other party", w=250)
d.final_named("f1", S, 415, "Offer withdrawn", side="b")
d.bar("fork", 180, 480, 300)
d.action("a6", B, 535, "6. Buyer signs:\nconsent, step-up\nlogin, e-mail OTP", w=160)
d.action("a7", S, 535, "7. Seller signs:\nconsent, step-up\nlogin, e-mail OTP", w=160)
d.note("n1", Y, 535, "Either party may sign first;\neligibility is rechecked at\ninitiate and at verify (D37)", w=215)
d.bar("join", 180, 600, 300)
d.action("a8", Y, 660, "8. Recheck both parties'\neligibility, the same terms\nfingerprint and the funding\nschedule (D67)", w=250)
d.decision("d2", Y, 740)
d.action("r1", 660, 740, "Reject the\nsignature; retry\nor withdraw", w=110)
d.action("a9", Y, 820, "9. Record the second\nsignature (SIGNED)", w=250)
d.action("a10", Y, 895, "10. Lock the required deposits\n(automatic retries)", w=250)
d.decision("d3", Y, 965)
d.action("a11", Y, 1045, "11. ACTIVE: finalize the reservation,\ninvalidate cancel requests;\ncontinue with BF-04", w=270)
d.final_named("f2", B, 1045, "Contract active", side="b")
d.action("a12", Y, 1135, "12. Stay SIGNED; notify both\nparties and the Operator", w=250)
d.decision("d4", Y, 1205)
d.action("a13", O, 1205, "13. Fix the technical\ncause; retry only the\nmissing legs", w=165)
d.note("n2", O, 1305, "Retrying does not reset\nthe 5-business-day\nwindow; a late lock\nsuccess still gives\nACTIVE", w=165)
d.action("a14", S, 1205, "14. Either party asks\nto cancel: consent,\nstep-up, e-mail OTP", w=165)
d.action("a15", Y, 1300, "15. Check: both asked, or one\nrequest standing 5 business days\nafter the first lock failure", w=260)
d.decision("d5", Y, 1375)
d.action("w1", B, 1375, "Wait; a party may\nwithdraw its own\nrequest before\nrefunds begin", w=160)
d.action("a16", Y, 1455, "16. ACTIVATION_REFUND_PENDING:\nstop lock retries, return every\nlocked deposit to its owner", w=260)
d.decision("d6", Y, 1530)
d.action("x1", O, 1530, "Alert the Operator;\nthe contract stays\npending", w=165)
d.action("a17", Y, 1600, "17. Zero lock: ACTIVATION_FAILED,\nrelease the reservation", w=260)
d.final_named("f3", S, 1600, "Activation failed", side="b")

d.flow("start", "b", "a1", "t")
d.flow("a1", "r", "a2", "l")
d.flow("a2", "b", "a3", "r", (Y, 200))
d.flow("a3", "b", "d1", "t")
d.flow("d1", "b", "a4", "t", label="[withdraw]", label_at=(S + 6, 292))
d.flow("a4", "r", "a5", "l")
d.flow("a5", "b", "f1", "r", (Y, 415))
d.flow("d1", "l", "fork", "t", (B, 275), d_off=B - 180, label="[agreed]", label_at=(B + 8, 257))
d.flow("fork", "b", "a6", "t", s_off=B - 180)
d.flow("fork", "b", "a7", "t", s_off=S - 180)
d.edge("n1", "a7", d.nodes["n1"].port("l"), d.nodes["a7"].port("r"), dashed=True, arrow=False)
d.flow("a6", "b", "join", "t", d_off=B - 180)
d.flow("a7", "b", "join", "t", d_off=S - 180)
d.flow("join", "b", "a8", "l", (320, 660), s_off=140)
d.flow("a8", "b", "d2", "t")
d.flow("d2", "b", "a9", "t", label="[valid]", label_at=(Y + 6, 757))
d.flow("d2", "r", "r1", "l", label="[invalid]", label_at=(Y + 18, 722))
d.flow("r1", "r", "a3", "r", (CH, 740), (CH, 225), d_off=25)
d.flow("a9", "b", "a10", "t")
d.flow("a10", "b", "d3", "t")
d.flow("d3", "b", "a11", "t", label="[all locked]", label_at=(Y + 6, 982))
d.flow("a11", "l", "f2", "r")
d.flow("d3", "r", "a12", "r", (700, 965), (700, 1135), label="[retries exhausted]", label_at=(Y + 22, 947))
d.flow("a12", "b", "d4", "t")
d.flow("d4", "r", "a13", "l", label="[retry]", label_at=(Y + 60, 1187))
d.flow("a13", "t", "a10", "r", (O, 895))
d.edge("n2", "a13", d.nodes["n2"].port("t"), d.nodes["a13"].port("b"), dashed=True, arrow=False)
d.flow("d4", "l", "a14", "r", label="[cancel]", label_at=(S + 95, 1187))
d.flow("a14", "b", "a15", "l", (S, 1285), d_off=-15)
d.flow("a15", "b", "d5", "t")
d.flow("d5", "l", "w1", "r", label="[not yet]", label_at=(S + 95, 1357))
d.flow("w1", "t", "a15", "l", (B, 1315), d_off=15)
d.flow("d5", "b", "a16", "t", label="[yes]", label_at=(Y + 6, 1392))
d.flow("a16", "b", "d6", "t")
d.flow("d6", "r", "x1", "l", label="[a refund failed]", label_at=(Y + 22, 1512))
d.flow("x1", "t", "a16", "r", (O, 1455))
d.flow("d6", "b", "a17", "t", label="[refunds confirmed]", label_at=(Y + 6, 1547))
d.flow("a17", "l", "f3", "r")

if __name__ == "__main__":
    d.write(Path(__file__).resolve().parent)
