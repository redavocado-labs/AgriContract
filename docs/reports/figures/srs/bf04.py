"""BF-04 Milestone Delivery & Settlement (activity diagram, UML / Visual Paradigm notation).

Content synced with the Phase 2 design (#662): per-milestone funding, READY evidence + consent on both weights,
mandatory Level 1.5 inspection, seller response window, dispute exits (D86), computed resolution and the GB-50
contest window (D85/D91), deposit-return remedy in the last settlement (D94), escrow clearance before SETTLED.
The few perpendicular crossings are drawn with a line jump. Final nodes sit in the parties' lanes.
"""
import sys
from pathlib import Path

sys.path.insert(0, str(Path(__file__).resolve().parents[1] / "tools"))
from vpdiagram import Diagram  # noqa: E402

d = Diagram("bf04", width=990, height=1975, allow_crossings=True)
for name, w in (("Buyer", 170), ("Seller", 170), ("Arbitrator", 150), ("Inspector", 150), ("System", 350)):
    d.lane(name, w)
B, S, A, I = (d.center(n) for n in ("Buyer", "Seller", "Arbitrator", "Inspector"))
Y = 805                     # System column
C1, C2, C3 = 940, 958, 976  # channels right of the System column
W = 240

d.initial("start", Y, 55)
d.action("a1", Y, 115, "1. Funding date due: request\nthe lock of the Buyer's payment\n(each milestone runs alone)", w=W)
d.decision("d1", Y, 185)
d.action("a2", Y, 255, "2. Stay CREATED; notify the\nparties; retry or BF-05\nrecovery", w=W)
d.final_named("f1", S, 330, "Continues in BF-05", side="b")
d.action("a3", S, 185, "3. Deliver; declare\nthe weight with\nREADY evidence\nand consent", w=150)
d.note("n1", B, 185, "Correction within\n1 h of the first\ndeclaration, before\nBuyer receipt", w=150)
d.action("a4", B, 290, "4. Record the\nreceived weight\nwith READY evidence\nand consent", w=150)
d.action("a5", Y, 410, "5. BUYER_RECEIVED: freeze\nthe seller weight, open the\nconfirmation window; request\nLevel 1.5 if it is mandatory", w=W)
d.bar("fork", Y, 480, 140)
d.decision("dB", B, 535)
d.action("a6", B, 600, "6. Confirm clean\nreceipt with\nexplicit consent", w=140)
d.action("a8", Y, 600, "8. Clean confirmation or Buyer\ntimeout: settle only when the\ninspection guard passes", w=W)
d.action("a7", B, 705, "7. Flag QUANTITY\nor QUALITY with\nevidence, consent", w=140)
d.action("a9", Y, 705, "9. AWAITING_SELLER_RESPONSE:\nno money or reputation effect", w=W)
d.decision("dC", Y, 775)
d.decision("dC2", S, 775)
d.action("a10", S, 850, "10. Contest the\nflag with consent", w=150)
d.action("a12", B, 870, "12. Dispute exit\n(either party):\nconcede, retract or\nsettle; consent,\nstep-up, OTP", w=140)
d.action("a11", Y, 855, "11. Seller silent: QUANTITY →\nBuyer weight, no fault;\nQUALITY → system contests", w=W)
d.decision("dD", Y, 925)
d.decision("mC", S, 985)
d.decision("m13", Y, 985)
d.action("a13", Y, 1050, "13. Request a Level 1.5\ninspection (a contest opens\na BreachCase)", w=W)
d.action("a14", I, 1050, "14. Inspect the\ngoods; submit\nthe report", w=130)
d.action("a15", Y, 1145, "15. Evaluate the confirmed report\n(INCONCLUSIVE twice: funds\nstay locked, Operator alerted)", w=W)
d.decision("dE", Y, 1215)
d.action("a16", Y, 1285, "16. COMPLETE: compute the\nquantity and quality", w=W)
d.decision("dF", Y, 1350)
d.action("a17", A, 1350, "17. Review and\napprove the\ncomputed\nresolution", w=130)
d.decision("dG", A, 1435)
d.action("a18", S, 1435, "18. The party at\nfault may contest\nonce within 2\nbusiness days", w=150)
d.decision("dH", S, 1525)
d.decision("m19", A, 1525)
d.action("a19", Y, 1525, "19. Finalize the settlement or\nremedy (quality concession:\nfault; quantity: no fault)", w=W)
d.decision("m20", Y, 1610)
d.action("a20", Y, 1690, "20. Milestone SETTLED; execute\nthe money legs (last milestone:\ndeposit-return remedy in the\nsame transaction)", w=W)
d.action("a21", Y, 1790, "21. Check: all milestones settled\nand escrow cleared (no open\nremedy leg, zero lock)", w=W)
d.decision("dI", Y, 1860)
d.final_named("f3", S, 1860, "Milestone settled;\ncontract stays ACTIVE", side="b")
d.final_named("f2", B, 1925, "Contract SETTLED", side="b")

d.flow("start", "b", "a1", "t")
d.flow("a1", "b", "d1", "t")
d.flow("d1", "b", "a2", "t", label="[not locked]", label_at=(Y + 6, 202))
d.flow("a2", "b", "f1", "r", (Y, 330))
d.flow("d1", "l", "a3", "r", label="[locked: IN_PROGRESS]", label_at=(I - 60, 167))
d.edge("n1", "a3", d.nodes["n1"].port("r"), d.nodes["a3"].port("l"), dashed=True, arrow=False)
d.flow("a3", "b", "a4", "r", (S, 290))
d.flow("a4", "b", "a5", "l", (B, 410))
d.flow("a5", "b", "fork", "t")
d.flow("fork", "b", "dB", "t", (Y - 50, 503), (B, 503), s_off=-50)
d.flow("fork", "b", "m13", "r", (Y + 50, 503), (C1, 503), (C1, 985), s_off=50, label="[mandatory]", label_at=(Y + 60, 507))
d.flow("dB", "b", "a6", "t", label="[clean]", label_at=(B + 6, 552))
d.flow("dB", "r", "a8", "t", (Y, 535), label="[timeout]", label_at=(S - 30, 517))
d.flow("a6", "r", "a8", "l")
d.flow("a8", "r", "m20", "r", (C2, 600), (C2, 1610), label="[guard passes]", label_at=(C2 - 92, 1592))
d.flow("dB", "l", "a7", "l", (8, 535), (8, 705), label="[issue]", label_at=(12, 517))
d.flow("a7", "r", "a9", "l")
d.flow("a9", "b", "dC", "t")
d.flow("dC", "l", "dC2", "r", label="[a party acts]", label_at=(A - 20, 757))
d.flow("dC2", "b", "a10", "t", label="[contest]", label_at=(S + 6, 792))
d.flow("dC2", "l", "a12", "t", (B, 775), label="[exit]", label_at=(B + 8, 757))
d.flow("dC", "b", "a11", "t", label="[seller silent]", label_at=(Y + 6, 792))
d.flow("a11", "b", "dD", "t")
d.flow("dD", "b", "m13", "t", label="[quality]", label_at=(Y + 6, 942))
d.flow("dD", "r", "a19", "r", (C3, 925), (C3, 1525), label="[quantity]", label_at=(Y + 22, 907))
d.flow("a10", "b", "mC", "t")
d.flow("mC", "r", "m13", "l")
d.flow("m13", "b", "a13", "t")
d.flow("a13", "l", "a14", "r")
d.flow("a14", "b", "a15", "l", (I, 1145))
d.flow("a15", "b", "dE", "t")
d.flow("dE", "r", "a13", "b", (930, 1215), (930, 1098), (Y, 1098), label="[INCONCLUSIVE]", label_at=(Y + 22, 1197))
d.flow("dE", "b", "a16", "t", label="[complete]", label_at=(Y + 6, 1232))
d.flow("a16", "b", "dF", "t")
d.flow("dF", "b", "a19", "t", label="[mandatory, clean]", label_at=(Y + 6, 1367))
d.flow("dF", "l", "a17", "r", label="[case]", label_at=(I - 20, 1332))
d.flow("a17", "b", "dG", "t")
d.flow("dG", "l", "a18", "r", label="[fault]", label_at=(345, 1417))
d.flow("dG", "b", "m19", "t", label="[no fault]", label_at=(A + 6, 1452))
d.flow("a18", "b", "dH", "t")
d.flow("dH", "r", "m19", "l", label="[expired]", label_at=(274, 1507))
d.flow("dH", "l", "mC", "l", (8, 1525), (8, 985), label="[contested]", label_at=(12, 1507))
d.flow("a12", "b", "m19", "b", (B, 1580), (A, 1580))
d.flow("m19", "r", "a19", "l")
d.flow("a19", "b", "m20", "t")
d.flow("m20", "b", "a20", "t")
d.flow("a20", "b", "a21", "t")
d.flow("a21", "b", "dI", "t")
d.flow("dI", "l", "f3", "r", label="[not yet]", label_at=(A - 20, 1842))
d.flow("dI", "b", "f2", "r", (Y, 1925), label="[cleared]", label_at=(Y + 6, 1877))

if __name__ == "__main__":
    d.write(Path(__file__).resolve().parent)
