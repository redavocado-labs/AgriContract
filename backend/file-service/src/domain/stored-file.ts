/*
 * The File aggregate of file-service-phase2-design.md §2: a blob plus its
 * technical metadata, agnostic of what the file is used for (the meaning is
 * in the field name of the owning service, e.g. cadastralExtractFileId).
 * Named StoredFile so it never shadows the DOM/Node `File` type.
 */

/** Set by the entrypoint the file came through, never declared by the caller (§2.1). */
export const INGEST_CHANNELS = [
  'DIRECT_UPLOAD',
  'EMAIL_INTAKE',
  'SYSTEM_GENERATED',
] as const;
export type IngestChannel = (typeof INGEST_CHANNELS)[number];

/** Technical state only (§2.2): is the blob intact and clean, not "is it approved". */
export const FILE_STATUSES = ['PROCESSING', 'READY', 'FAILED'] as const;
export type FileStatus = (typeof FILE_STATUSES)[number];

/** The bytes were stored; what file-service knows about them (§2, §8). */
export interface StoredFile {
  /** Plain UUID; also the object key in storage (§2.3). Generated by file-service. */
  fileId: string;
  /** SHA-256 hex of the stored bytes, computed while they streamed (§2). */
  storageHash: string;
  /** userId (DIRECT_UPLOAD) or serviceId (SYSTEM_GENERATED). */
  uploadedBy: string;
  ingestChannel: IngestChannel;
  contentType: string;
  /** Bytes actually stored, counted while streaming (not the declared length). */
  fileSize: number;
  status: FileStatus;
  /** Set by confirm-attached once the owning service kept the fileId (§7). */
  attached: boolean;
  /** Blocks every deletion while set (§7). Set by an Admin, never by file-service. */
  legalHold: boolean;
  /** Tombstone of the two-step deletion (§7); the blob goes after it. Null while kept. */
  deletedAt: Date | null;
  /**
   * The caller's Idempotency-Key, unique per uploadedBy (D60); null when the
   * entrypoint has none.
   */
  idempotencyKey: string | null;
}

/**
 * A freshly stored file, not attached (§7): PROCESSING until the virus scan
 * decides (§2.2), or READY at once for a file that is not scanned
 * (SYSTEM_GENERATED, §3).
 */
export function newStoredFile(
  fields: Pick<
    StoredFile,
    | 'fileId'
    | 'storageHash'
    | 'uploadedBy'
    | 'ingestChannel'
    | 'contentType'
    | 'fileSize'
    | 'idempotencyKey'
  >,
  status: 'PROCESSING' | 'READY' = 'PROCESSING',
): StoredFile {
  return {
    ...fields,
    status,
    attached: false,
    legalHold: false,
    deletedAt: null,
  };
}

/**
 * Whether GET serves the file (supplementary-services-api.yaml getFile: "404
 * Not found or not READY"): READY and not deleted. A file still being
 * scanned, a rejected one and a deleted one look the same to the caller.
 */
export function isReadable(file: StoredFile): boolean {
  return file.status === 'READY' && file.deletedAt === null;
}
